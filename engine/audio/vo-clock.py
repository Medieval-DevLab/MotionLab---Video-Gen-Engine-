"""VO clock without a speech model: speech runs from ffmpeg silencedetect, matched 1:1 to the script's phrases.

usage: python -I engine/audio/vo-clock.py <vo audio> <phrases.txt> <out timing.js> [--hold 3.0] [--db -40] [--min 0.18]

phrases.txt: one spoken phrase per line, in script order, split where the voice pauses (commas, full stops,
ellipses). '# act N' starts an act; '## sNN' starts a segment. If the run count != phrase count it stops and
prints both lists so the phrases (or --db / --min) can be adjusted; it never guesses.
Where the voice runs on without a pause, start the next line with '+ ': it shares the run above and the run's time
is split between them by syllables. A line of just '~' is a run that is not speech (a breath); it is skipped.
"""
import json, os, re, subprocess, sys, statistics

args = sys.argv[1:]
def opt(k, d):
    return float(args[args.index(k) + 1]) if k in args else d
vo, phrases_file, out = args[0], args[1], args[2]
HOLD, DB, MIN = opt('--hold', 3.0), opt('--db', -40), opt('--min', 0.18)

err = subprocess.run(['ffmpeg', '-hide_banner', '-nostdin', '-i', vo, '-af', f'silencedetect=noise={DB}dB:d={MIN}', '-f', 'null', '-'],
                     capture_output=True, text=True).stderr
h, m, s = re.search(r'Duration: (\d+):(\d+):([\d.]+)', err).groups(); dur = int(h) * 3600 + int(m) * 60 + float(s)
runs, prev, start = [], 0.0, None
for line in err.splitlines():
    a = re.search(r'silence_start: ([\d.]+)', line)
    if a: start = float(a.group(1))
    b = re.search(r'silence_end: ([\d.]+)', line)
    if b:
        if start > prev + 0.05: runs.append((prev, start))
        prev = float(b.group(1))
if dur > prev + 0.05: runs.append((prev, dur))

segs, act, cur, phrases, groups = [], 1, None, [], []   # groups: the phrases of each speech run ([] = not speech)
for raw in open(phrases_file, encoding='utf-8').read().splitlines():
    line = raw.strip()
    if not line: continue
    if line.startswith('## '): cur = {'id': line[3:].strip(), 'act': act, 'idx': []}; segs.append(cur); continue
    if line.startswith('# act'): act = int(line.split()[-1]); continue
    if line.startswith('#'): continue
    if line == '~': groups.append([]); continue
    cont = line.startswith('+ ')
    if cont: line = line[2:].strip()
    cur['idx'].append(len(phrases)); phrases.append(line)
    if cont and groups and groups[-1]: groups[-1].append(len(phrases) - 1)
    else: groups.append([len(phrases) - 1])

if len(runs) != len(groups):
    print(f'MISMATCH: {len(runs)} speech runs vs {len(groups)} phrase runs. Fix the phrase split or --db/--min.')
    for i in range(max(len(runs), len(groups))):
        r = f'{runs[i][0]:7.2f}-{runs[i][1]:7.2f} ({runs[i][1]-runs[i][0]:4.2f})' if i < len(runs) else ' ' * 24
        print(f'{i:3d} {r}  {" + ".join(phrases[k] for k in groups[i]) or "~" if i < len(groups) else ""}')
    sys.exit(1)

def syl(w): return max(1, len(re.findall(r'[aeiouy]+', w.lower())))
sy = [sum(syl(w) for w in re.findall(r"[A-Za-z']+", p)) for p in phrases]
rates = [(i, sum(sy[k] for k in g) / max(0.01, b - a)) for i, ((a, b), g) in enumerate(zip(runs, groups)) if g]
med = statistics.median(r for _, r in rates)
for i, r in rates:
    if r > med * 1.6 or r < med / 1.6: print(f'check {i} {runs[i][0]:.2f}-{runs[i][1]:.2f} {r:.1f} syl/s: {" + ".join(phrases[k] for k in groups[i])}')

# each phrase's time; phrases that share a run split it by syllables
pt, first, prev_end = {}, {}, {}
for gi, ((a, b), g) in enumerate(zip(runs, groups)):
    tot, acc = sum(sy[k] for k in g), 0
    for j, k in enumerate(g):
        pt[k] = (a + (b - a) * acc / tot, b if j == len(g) - 1 else a + (b - a) * (acc + sy[k]) / tot); acc += sy[k]
        first[k] = j == 0; prev_end[k] = runs[gi - 1][1] if gi else 0.0
END = round(runs[-1][1] + HOLD, 2)
bound = lambda k: 0.0 if k == 0 else round((prev_end[k] + pt[k][0]) / 2 if first[k] else pt[k][0], 2)
out_segs = []
for s in segs:
    f, l = s['idx'][0], s['idx'][-1]
    out_segs.append({'id': s['id'], 'act': s['act'], 't0': bound(f), 't1': bound(l + 1) if l + 1 < len(phrases) else END,
                     'lines': [{'t0': round(pt[k][0], 2), 't1': round(pt[k][1], 2), 'text': phrases[k]} for k in range(f, l + 1)]})
data = {'vo': os.path.basename(vo), 'voDur': round(dur, 2), 'dur': END, 'segments': out_segs}
open(out, 'w', encoding='utf-8').write(f'// VO clock: {len(runs)} speech runs (ffmpeg silencedetect {DB:g} dB, {MIN:g} s) matched 1:1 to {len(phrases)} script phrases. Generated by engine/audio/vo-clock.py.\nwindow.TIMING = ' + json.dumps(data, indent=1) + ';\n')
print(f'OK {len(runs)} runs = {len(groups)} phrase runs ({len(phrases)} phrases) | {len(out_segs)} segments | VO {dur:.2f} s | film {END} s | median {med:.2f} syl/s -> {out}')
